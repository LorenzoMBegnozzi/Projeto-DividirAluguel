-- conversas, mensagens, pagamentos, notificacoes, bloqueios e denuncias usam sequência (não
-- IDENTITY): são as tabelas com RLS (V2), e o "INSERT ... RETURNING id" que o Hibernate faz para
-- IDENTITY também checa a política de SELECT da linha retornada — quebra sempre que a linha é
-- inserida para outra pessoa (ex.: notificação para o dono do anúncio). SEQUENCE não usa RETURNING.
CREATE SEQUENCE seq_conversas INCREMENT BY 1;
CREATE SEQUENCE seq_mensagens INCREMENT BY 1;
CREATE SEQUENCE seq_pagamentos INCREMENT BY 1;
CREATE SEQUENCE seq_notificacoes INCREMENT BY 1;
CREATE SEQUENCE seq_bloqueios INCREMENT BY 1;
CREATE SEQUENCE seq_denuncias INCREMENT BY 1;

CREATE TABLE conversas (
    id              BIGINT      PRIMARY KEY DEFAULT nextval('seq_conversas'),
    anuncio_id      BIGINT      NOT NULL,
    inquilino_id    BIGINT      NOT NULL,
    usuario2_id     BIGINT,
    criado_em       TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_conversas_anuncio FOREIGN KEY (anuncio_id) REFERENCES anuncios (id) ON DELETE CASCADE,
    CONSTRAINT fk_conversas_inquilino FOREIGN KEY (inquilino_id) REFERENCES usuarios (id) ON DELETE CASCADE,
    CONSTRAINT fk_conversas_usuario2 FOREIGN KEY (usuario2_id) REFERENCES usuarios (id) ON DELETE CASCADE
);

CREATE INDEX idx_conversas_inquilino ON conversas (inquilino_id);

-- No máximo uma conversa por (anúncio, inquilino) com o dono.
CREATE UNIQUE INDEX uq_conversas_com_dono ON conversas (
    (CASE WHEN usuario2_id IS NULL THEN anuncio_id END),
    (CASE WHEN usuario2_id IS NULL THEN inquilino_id END)
);

-- No máximo uma conversa por (anúncio, par de interessados), independente de quem iniciou:
-- usa o menor/maior id do par para o índice enxergar os dois sentidos como a mesma combinação.
CREATE UNIQUE INDEX uq_conversas_entre_interessados ON conversas (
    (CASE WHEN usuario2_id IS NOT NULL THEN anuncio_id END),
    (CASE WHEN usuario2_id IS NOT NULL THEN LEAST(inquilino_id, usuario2_id) END),
    (CASE WHEN usuario2_id IS NOT NULL THEN GREATEST(inquilino_id, usuario2_id) END)
);

CREATE TABLE mensagens (
    id                  BIGINT              PRIMARY KEY DEFAULT nextval('seq_mensagens'),
    conversa_id         BIGINT              NOT NULL,
    remetente_id        BIGINT              NOT NULL,
    conteudo            VARCHAR(2000)       NOT NULL,
    enviado_em          TIMESTAMP           NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_mensagens_conversa FOREIGN KEY (conversa_id) REFERENCES conversas (id) ON DELETE CASCADE,
    CONSTRAINT fk_mensagens_remetente FOREIGN KEY (remetente_id) REFERENCES usuarios (id) ON DELETE CASCADE
);

CREATE INDEX idx_mensagens_conversa ON mensagens (conversa_id, enviado_em);

CREATE TABLE interesses (
