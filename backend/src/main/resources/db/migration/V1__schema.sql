-- Schema inicial do RachaAi em PostgreSQL. Substitui o histórico de 35 migrations que existiu
-- em Oracle: como o projeto ainda não tinha ido para produção (sem dados reais a preservar),
-- a troca de banco foi feita consolidando o estado final direto num baseline novo, em vez de
-- traduzir cada ALTER TABLE Oracle um a um. RLS (políticas por linha) fica na V2, separado.

CREATE TABLE usuarios (
    id                          BIGINT              GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome                        VARCHAR(120)        NOT NULL,
    email                       VARCHAR(180)        NOT NULL,
    senha_hash                  VARCHAR(255)        NOT NULL,
    data_nascimento             DATE                NOT NULL,
    cpf                         VARCHAR(11),
    alugar                      BOOLEAN             NOT NULL DEFAULT FALSE,
    anunciar                    BOOLEAN             NOT NULL DEFAULT FALSE,
    tipo_anunciante             VARCHAR(20),
    ocupacao                    VARCHAR(160),
    bio                         VARCHAR(1000),
    criado_em                   TIMESTAMP           NOT NULL DEFAULT CURRENT_TIMESTAMP,
    termos_seguranca_aceito_em  TIMESTAMP,
    admin                       BOOLEAN             NOT NULL DEFAULT FALSE,
    bloqueado_em                TIMESTAMP,
    motivo_bloqueio             VARCHAR(500),
    bloqueado_por_id            BIGINT,
    versao_token                INTEGER             NOT NULL DEFAULT 0,
    termos_aceitos_em           TIMESTAMP,
    versao_termos               VARCHAR(20),
    excluido_em                 TIMESTAMP,
    email_confirmado_em         TIMESTAMP,
    CONSTRAINT uq_usuarios_email UNIQUE (email),
    CONSTRAINT uq_usuarios_cpf UNIQUE (cpf),
    CONSTRAINT fk_usuarios_bloqueado_por FOREIGN KEY (bloqueado_por_id) REFERENCES usuarios (id) ON DELETE SET NULL,
    CONSTRAINT ck_usuarios_tipo_anunciante CHECK (tipo_anunciante IS NULL OR tipo_anunciante IN ('VAGA', 'ESTABELECIMENTO')),
    CONSTRAINT ck_usuarios_papel_minimo CHECK (alugar OR anunciar)
);

